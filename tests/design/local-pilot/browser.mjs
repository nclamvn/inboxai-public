import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { readFileSync,writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { audit } from '../browser.mjs'
import { rehearseWorkspaceUI } from '../ui-workspace.mjs'
import { button,signIn } from './fixture.mjs'

const link=(page,name)=>page.getByRole('link',{name,exact:true})
const status=(page,text)=>page.getByRole('status').filter({hasText:text}).waitFor()
const require=createRequire(import.meta.url)
const axeScript=readFileSync(require.resolve('axe-core/axe.min.js'),'utf8')
export async function rehearseLocalPilot({guide,app,base,email,previousEmail,password,record,output}) {
  const browser=await chromium.launch({channel:'chrome',proxy:{server:'http://127.0.0.1:1',bypass:'127.0.0.1'}})
  const {seed}=guide
  const errors=[]
  async function login(address,viewport) {
    const page=await signIn(browser,app,address,password,viewport)
    page.on('pageerror',error=>errors.push(error.message))
    await page.context().route('**/*',route=>[app,base,guide.origin].includes(new URL(route.request().url()).origin)?route.continue():route.abort())
    return page
  }
  async function capture(page,name) {
    // The guide keeps its no-inline-script CSP; evaluate through the driver.
    await page.evaluate(axeScript)
    assert.deepEqual(await audit(page),[])
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:output+'/'+name+'.png',animations:'disabled',fullPage:true})
  }
  let desktop,mobile
  try {
    desktop=await login(email)
    const guidePage=await desktop.context().newPage()
    await guidePage.goto(guide.origin)
    await guidePage.getByText('Đang chạy đúng mã nguồn',{exact:true}).waitFor()
    const config=await(await guidePage.request.get(guide.origin+'/config')).json()
    const headers={Origin:guide.origin,'X-Demo-Token':config.token}
    const control=async(name,data={})=>{
      const response=await guidePage.request.post(guide.origin+'/'+name,{headers,data,timeout:90_000})
      assert.equal(response.status(),200,await response.text())
      return response.json()
    }
    assert.equal((await guidePage.request.post(guide.origin+'/corrected')).status(),403)
    assert.equal((await guidePage.request.post(guide.origin+'/corrected',{headers:{...headers,Origin:'https://untrusted.example'}})).status(),403)
    assert.equal((await guidePage.request.post(guide.origin+'/reset',{headers,data:{confirm:'no'}})).status(),400)
    assert.equal((await guidePage.request.post(guide.origin+'/corrected',{headers})).status(),409)
    assert.equal(await desktop.locator('[data-pilot-version]').getAttribute('data-pilot-version'),guide.version.fingerprint)
    assert.ok(seed.mailCount>100,'The trial must contain more than 100 synchronized tenant-owned emails, not just fixture deliveries')
    await guidePage.getByText(seed.mailCount+' thư đã đồng bộ · 2 Gmail giả lập',{exact:true}).waitFor()
    await rehearseWorkspaceUI({page:desktop,app,output,record})
    await capture(guidePage,'01-guide-desktop')
    record('The guide and authenticated app identify the same source fingerprint; cross-origin, unconfirmed reset and premature supplier controls are denied.',true)

    const row=page=>page.getByRole('region',{name:'Hồ sơ mua hàng cần xử lý'}).getByRole('listitem').filter({has:page.getByRole('heading',{name:new RegExp('^'+seed.po+' ·')})})
    const panel=page=>row(page).getByRole('region',{name:'Yêu cầu và theo dõi chứng từ'})
    await row(desktop).getByText(seed.reason,{exact:true}).waitFor()
    await row(desktop).getByRole('link',{name:/^Email hóa đơn/}).click()
    await desktop.waitForURL(url=>url.pathname==='/inbox'&&url.searchParams.has('email'))
    const source=await desktop.url()
    await desktop.goto(config.ledger)
    await desktop.getByRole('heading',{name:'Lịch sử',exact:true}).waitFor()
    const ledger=await seed.request('/api/commitments/'+seed.orderId)
    assert.ok(ledger.history.length&&ledger.history[0].sources.length)
    await desktop.goto(app+'/inbox')
    await button(panel(desktop),'Soạn yêu cầu gửi nhà cung cấp').click()
    await desktop.waitForURL('**/compose?reply=*')
    const compose=desktop.url()
    const body=await desktop.getByLabel('Nội dung thư').inputValue()
    const edited=body+'\nNhờ gửi bản xác minh trước 15 giờ để kịp lịch duyệt.'
    await desktop.getByLabel('Nội dung thư').fill(edited)
    await button(desktop,'Lưu bản nháp').click()
    await desktop.getByText('Bản nháp đã lưu',{exact:true}).waitFor()
    record('Action Inbox opens the exact invoice source and persistent ledger. A buyer-reviewed request draft is saved through the production reply API.',true)

    mobile=await login(email,{width:390,height:844})
    await mobile.goto(compose)
    assert.equal(await mobile.getByLabel('Nội dung thư').inputValue(),edited)
    const before=await guide.readState()
    await mobile.context().setOffline(true)
    await control('restart')
    await mobile.context().setOffline(false)
    await mobile.context().close()
    mobile=await login(email,{width:390,height:844})
    await mobile.goto(compose)
    assert.equal(await mobile.getByLabel('Nội dung thư').inputValue(),edited)
    assert.equal((await guide.readState()).request.draftId,before.request.draftId)
    await capture(mobile,'02-mobile-draft-restored')
    record('An independent mobile session restores the desktop draft; offline transport, application restart and browser-context reopening preserve the same draft and ledger.',true)

    await mobile.goto(config.ask)
    await mobile.getByText('Có mâu thuẫn giữa các email',{exact:true}).waitFor()
    const citations=mobile.getByRole('link',{name:/^Mở nguồn ·/})
    assert.ok(await citations.count()>=3)
    const answer=await seed.request('/api/ask-inbox/answer',{method:'POST',headers:{'content-type':'application/json'},
      body:JSON.stringify({query:'Hạn thanh toán và tổng tiền hóa đơn của '+seed.po+'?'})})
    assert.equal(answer.status,'conflicting')
    assert.equal(answer.claims.find(item=>item.field==='invoiceTotal').observations[0].value.minor,'60000')
    const dates=answer.claims.find(item=>item.field==='paymentDue')
    assert.deepEqual(new Set(dates.observations.map(item=>item.value.iso)),new Set([seed.oldDue,seed.due]))
    await capture(mobile,'03-ask-cross-account-mobile')
    await citations.first().click()
    await mobile.waitForURL('**/search/source?*')
    record('Ask Inbox compares exact VND amounts and retains both conflicting dates across the two Gmail accounts. Its version-bound citation opens the actual source on mobile.',true)

    await mobile.goto(compose)
    await button(mobile,'Xem trước thư gửi').click()
    const preview=mobile.getByRole('dialog',{name:'Xem trước thư gửi'})
    await preview.getByText(seed.accounts['mua-hang'].address,{exact:true}).waitFor()
    await preview.getByText(seed.supplier,{exact:true}).waitFor()
    assert.equal((await guide.readState()).sent,0)
    await control('lose-receipt')
    await button(preview,'Xác nhận gửi').click()
    await button(mobile,'Kiểm tra trạng thái gửi').waitFor()
    await control('restart')
    await mobile.reload()
    await button(mobile,'Kiểm tra trạng thái gửi').click()
    await link(mobile,'Mở thư đã gửi').waitFor()
    assert.equal((await guide.readState()).sent,1)
    await capture(mobile,'04-approved-send-mobile')
    record('Mobile approval freezes the sender and recipients. A lost Gmail fixture acknowledgement plus restart reconciles exactly one send; the guide never sends on the user’s behalf.',true)

    const accountant=await login(seed.reviewer,{width:390,height:844})
    assert.equal((await accountant.request.get(app+'/api/commitments/evidence-requests?case='+seed.handoffId)).status(),404)
    const outsider=await login(previousEmail)
    assert.equal((await outsider.request.get(app+'/api/commitments/'+seed.orderId)).status(),404)
    assert.equal((await outsider.request.get(app+'/api/emails/'+new URL(source).searchParams.get('email'))).status(),404)
    await control('missing')
    await desktop.goto(app+'/inbox')
    await panel(desktop).getByText('Đã có hồi đáp; hồ sơ vẫn chờ chứng từ được kiểm tra và duyệt.',{exact:true}).waitFor()
    const files=row(desktop).getByRole('region',{name:'Chứng từ bổ sung từ email'})
    await files.locator('summary').click()
    await files.getByText('Tệp chưa có hạn thanh toán được yêu cầu · hoa-don.csv',{exact:true}).waitFor()
    assert.equal(await link(files,'Xem trước chứng từ mới').count(),0)
    assert.equal((await guide.readState()).invoice,seed.original)
    await capture(desktop,'05-missing-evidence-held')
    record('A supplier response and same-name CSV without the requested due date leave the original invoice intact. Accountant and outsider cannot read the buyer request or foreign ledger.',true)

    await guidePage.bringToFront()
    await guidePage.reload()
    await button(guidePage,'Nạp chứng từ hợp lệ').click()
    await guidePage.getByRole('status').filter({hasText:'Đã nạp tình huống.'}).waitFor()
    await control('corrected')
    await desktop.reload()
    const currentFiles=row(desktop).getByRole('region',{name:'Chứng từ bổ sung từ email'})
    await link(currentFiles,'Xem trước chứng từ mới').click()
    await button(desktop,'Ghi nhận hóa đơn').click()
    await status(desktop,'Đã ghi nhận chứng từ.')
    await link(desktop,'Mở hồ sơ đối soát').click()
    await button(desktop,'Bàn giao bản bổ sung').click()
    await status(desktop,'Đã bàn giao hồ sơ cho Kế toán.')
    await accountant.goto((await guide.readState()).handoff)
    await button(accountant,'Duyệt bản bổ sung').click()
    await status(accountant,'Đã duyệt hồ sơ.')
    await accountant.reload()
    await accountant.getByText('Đã khép ngoại lệ',{exact:true}).waitFor()
    await capture(accountant,'06-accountant-approval-mobile')
    const closed=await guide.readState()
    assert.equal(closed.stage,'closed');assert.equal(closed.invoice,seed.corrected);assert.equal(closed.request.tracking,false)
    assert.equal(closed.sent,1)
    await control('restart')
    assert.equal((await guide.readState()).decision,closed.decision)
    record('Repeated fixture delivery creates one correction. The buyer hands over its exact evidence and a separate mobile accountant approves; closure and the same decision survive restart without extra sends.',true)

    await desktop.goto(config.operator)
    await desktop.getByRole('textbox',{name:'Lệnh thao tác'}).fill('Lưu trữ thư từ offers@example.test')
    await desktop.getByLabel('Tài khoản thư',{exact:true}).selectOption(seed.accounts['mua-hang'].id)
    await button(desktop,'Xem trước kế hoạch').click()
    const plan=desktop.getByRole('region',{name:'Bản xem trước kế hoạch'})
    await plan.getByRole('checkbox').first().waitFor()
    const selected=await plan.getByRole('checkbox').count()
    assert.ok(selected>0)
    await button(plan,'Xem lại phạm vi đã chọn').click()
    await button(desktop.getByRole('dialog',{name:'Phê duyệt phạm vi'}),'Phê duyệt phạm vi này').click()
    await plan.getByRole('button',{name:/^Thực thi \d+ thư$/}).click()
    const outcome=desktop.getByRole('region',{name:'Xác minh và hoàn tác'})
    await outcome.getByRole('status').filter({hasText:'Đã xác minh'}).waitFor()
    await capture(desktop,'07-operator-verified')
    await button(outcome,'Xem trước hoàn tác').click()
    await button(desktop.getByRole('dialog',{name:'Xác nhận hoàn tác'}),'Hoàn tác phạm vi này').click()
    await outcome.getByRole('status').filter({hasText:'Đã hoàn tác'}).waitFor()
    assert.equal((await guide.readState()).sent,1)
    record('AI Operator previews the same fixture mail, freezes the approved scope, executes, verifies and explicitly undoes the archive. No additional email is sent.',true)

    await guidePage.setViewportSize({width:390,height:844})
    await guidePage.reload()
    await guidePage.getByText('Đã khép hồ sơ',{exact:true}).waitFor()
    await capture(guidePage,'08-guide-mobile-closed')
    await guidePage.context().setOffline(true)
    await guidePage.evaluate(()=>window.dispatchEvent(new Event('focus')))
    await guidePage.getByRole('status').filter({hasText:'Chưa đọc được trạng thái.'}).waitFor()
    await guidePage.context().setOffline(false)
    await guidePage.evaluate(()=>window.dispatchEvent(new Event('focus')))
    await guidePage.getByRole('status').filter({hasText:'Đã kết nối lại bản thử.'}).waitFor()
    assert.equal((await guide.readState()).decision,closed.decision)
    await guidePage.locator('summary').click()
    await guidePage.getByLabel('Nhập ĐẶT LẠI để khôi phục bộ ban đầu').fill('ĐẶT LẠI')
    await button(guidePage,'Khôi phục bộ giả lập').click()
    await guidePage.getByRole('status').filter({hasText:'Đã khôi phục bộ ban đầu.'}).waitFor({timeout:90_000})
    const reset=await guide.readState()
    assert.equal(reset.generation,2);assert.equal(reset.request,null);assert.equal(reset.sent,0);assert.equal(reset.invoice,seed.original)
    assert.equal(reset.corrected,false)
    const fresh=await login(email,{width:390,height:844})
    await row(fresh).getByText(seed.reason,{exact:true}).waitFor()
    await capture(fresh,'09-ready-to-try-mobile')
    assert.deepEqual(errors,[])
    writeFileSync(output+'/workflow.json',JSON.stringify({version:guide.version,chrome:browser.version(),
      provenance:'Synthetic users, two loopback Gmail accounts, real local APIs and PostgreSQL; deterministic Ask Inbox; no model/provider API calls.',
      initialInvoice:seed.original,approvedInvoice:seed.corrected,decision:closed.decision,
      initialSyncedGmailEmails:seed.mailCount,acceptedSendsBeforeReset:closed.sent,restoredGeneration:reset.generation},null,2)+'\n')
    record('The explicit local-only restore recreates the initial database and provider state, clears trial sends and corrections, and reopens the initial task after a real login. Audited desktop/mobile screens pass axe and overflow checks.',true)
  } catch(error) {
    await mobile?.screenshot({path:output+'/failure-mobile.png'}).catch(()=>{})
    await desktop?.screenshot({path:output+'/failure-desktop.png'}).catch(()=>{})
    throw error
  } finally { await browser.close() }
}
